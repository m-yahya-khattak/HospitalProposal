const times = (source: string, n = 1): Formula => ({
  type: "timesSource",
  source,
  n,
});
const per = (source: string, n: number): Formula => ({
  type: "perSource",
  source,
  n,
});
const exists = (source: string, n = 1): Formula => ({
  type: "oneIfExists",
  source,
  n,
});

function item(
  id: string,
  name: string,
  category: CatalogItem["category"],
  premiumUnit: number,
  budgetUnit: number,
  contributions: Formula[],
  enabled = true,
): CatalogItem {
  return { id, name, category, premiumUnit, budgetUnit, enabled, contributions };
}

